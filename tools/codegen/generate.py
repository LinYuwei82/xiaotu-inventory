#!/usr/bin/env python3
"""表结构与版本能力驱动的代码生成器。

输入：schema/*.json
输出：DAO、服务层、HTTP 路由、前端列表/表单页、CMake 源文件清单、版本能力头文件

生成物带固定标记头，集中在 *_gen 目录，重新生成会整体覆盖；
需要自定义逻辑时写在 core/src/handwritten/ 等手写目录，通过组合方式扩展。

用法：
    python3 tools/codegen/generate.py                    # 生成 schema/ 下全部定义
    python3 tools/codegen/generate.py --schema masterdata
    python3 tools/codegen/generate.py --check            # 只校验不写盘
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
TEMPLATE_DIR = HERE / "templates"
MARKER = "AUTO-GENERATED by tools/codegen"

CPP_TYPES = {"string": "std::string", "int": "std::int64_t", "bool": "bool"}


def cpp_literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def struct_default(field_type: str, default) -> str:
    if field_type == "string":
        return f" = {cpp_literal(str(default))}"
    if field_type == "bool":
        return " = true" if default else " = false"
    return f" = {int(default)}"


def json_default(field_type: str, default):
    if field_type == "string":
        return cpp_literal(str(default))
    if field_type == "bool":
        return "true" if default else "false"
    return str(int(default))


def prepare_table(table: dict) -> dict:
    fields = []
    for raw in table["fields"]:
        field_type = raw.get("type", "string")
        if field_type not in CPP_TYPES:
            raise SystemExit(f"字段 {raw['name']} 的类型不受支持: {field_type}")
        default = raw.get("default", "" if field_type == "string" else False if field_type == "bool" else 0)
        fields.append(
            {
                **raw,
                "type": field_type,
                "cpp": CPP_TYPES[field_type],
                "default": default,
                "default_cpp": struct_default(field_type, default),
                "json_default": json_default(field_type, default),
                "reference": raw.get("reference"),
                "sync_to": raw.get("sync_to", ""),
                "options_api": raw.get("options_api", ""),
                "bind_expr": (
                    f"static_cast<std::int64_t>(row.{raw['name']} ? 1 : 0)"
                    if field_type == "bool"
                    else f"row.{raw['name']}"
                ),
                "read_expr": (
                    f"stmt.i64({len(fields) + 1}) != 0"
                    if field_type == "bool"
                    else f"stmt.text({len(fields) + 1})"
                    if field_type == "string"
                    else f"stmt.i64({len(fields) + 1})"
                ),
            }
        )

    columns = ", ".join(f["name"] for f in fields)
    names = {f["name"] for f in fields}
    return {
        **table,
        "Name": "".join(part.capitalize() for part in table["table"].split("_")),
        "fields": fields,
        "unique_fields": [f for f in fields if f.get("unique")],
        "audit_column": "code" if "code" in names else "name" if "name" in names else "",
        "select_columns": f"id, {columns}",
        "insert_columns": f"{columns}, ",
        "value_placeholders": ", ".join(["?"] * len(fields)) + ", ",
        "update_set": ", ".join(f"{f['name']} = ?" for f in fields) + ", ",
    }


def render(env: Environment, template: str, context: dict) -> str:
    text = env.get_template(template).render(**context)
    if not text.startswith(("//", "/*")):
        text = text.lstrip("\n")
    return text


DRIFT: list[Path] = []


def write(path: Path, content: str, check: bool) -> None:
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if check:
        if existing != content:
            print(f"[drift] {path.relative_to(ROOT)}")
            DRIFT.append(path)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    if existing != content:
        path.write_text(content, encoding="utf-8")
        print(f"生成 {path.relative_to(ROOT)}")


def clean_stale(directory: Path, keep: set[Path], suffixes: tuple[str, ...], check: bool) -> None:
    if not directory.exists() or check:
        return
    for path in directory.iterdir():
        if path.is_file() and path not in keep and path.name.endswith(suffixes):
            head = path.read_text(encoding="utf-8", errors="ignore")[:120]
            if MARKER in head:
                path.unlink()
                print(f"清理 {path.relative_to(ROOT)}")


STATE_VALUES = {"full", "limited", "hidden"}

TABLE_SUFFIXES = (
    "_dao.h",
    "_dao.cpp",
    "_service.h",
    "_service.cpp",
    "_routes.h",
    "_routes.cpp",
    "_page.js",
)


def prepare_edition(edition: dict) -> dict:
    code = edition["code"]
    name = "".join(part.capitalize() for part in code.replace("-", "_").split("_"))
    feature_rows = []
    for key, state in edition.get("features", {}).items():
        if state not in STATE_VALUES:
            raise SystemExit(f"版本 {code} 的能力 {key} 状态不受支持: {state}")
        feature_rows.append({"key": key, "state": state})
    quota_rows = [{"key": key, "limit": int(limit)} for key, limit in edition.get("quotas", {}).items()]
    return {**edition, "Name": name, "feature_rows": feature_rows, "quota_rows": quota_rows}


def generate_editions(path: Path, schema: dict, env: Environment, check: bool) -> int:
    editions = [prepare_edition(item) for item in schema["editions"]]
    codes = [item["code"] for item in editions]
    default_code = schema.get("default", codes[0])
    if default_code not in codes:
        raise SystemExit(f"默认版本不在能力表中: {default_code}")

    context = {
        "schema": {**schema, "default": default_code},
        "editions": editions,
        "default_index": codes.index(default_code),
        "source": path.name,
    }
    content = render(env, schema.get("template", "edition_caps.h.j2"), context)
    output = ROOT / schema["targets"]["core_include"] / schema.get("output", "edition_caps.h")
    write(output, content, check)
    print(f"完成：{len(editions)} 个版本")
    return 0


def generate_tables(schema: dict, env: Environment, check: bool) -> int:
    targets = schema["targets"]
    generated: dict[str, list[Path]] = {name: [] for name in targets}
    pages = []

    for table in schema["tables"]:
        prepared = prepare_table(table)
        context = {"schema": schema, "t": prepared}
        key = prepared["key"]

        files = {
            "core_include": (f"{key}_dao.h", "dao.h.j2"),
            "core_src": (f"{key}_dao.cpp", "dao.cpp.j2"),
            "core_include_service": (f"{key}_service.h", "service.h.j2"),
            "core_src_service": (f"{key}_service.cpp", "service.cpp.j2"),
            "server_include": (f"{key}_routes.h", "routes.h.j2"),
            "server_src": (f"{key}_routes.cpp", "routes.cpp.j2"),
            "web": (f"{key}_page.js", "page.js.j2"),
        }

        for target, (filename, template) in files.items():
            target_key = target.replace("_service", "")
            directory = ROOT / targets[target_key]
            content = render(env, template, context)
            write(directory / filename, content, check)
            generated[target_key].append(directory / filename)

        pages.append(
            {
                "key": key,
                "title": prepared["entity"],
                "script": f"/gen/{key}_page.js",
            }
        )

    manifest = json.dumps(pages, ensure_ascii=False, indent=2) + "\n"
    write(ROOT / targets["web"] / "pages.json", manifest, check)
    generated["web"].append(ROOT / targets["web"] / "pages.json")

    core_sources = sorted(generated["core_src"])
    server_sources = sorted(generated["server_src"])
    cmake_lines = [
        "# AUTO-GENERATED by tools/codegen. DO NOT EDIT.",
        "set(XIAOTU_GENERATED_CORE_SOURCES",
        *[f'  "${{CMAKE_SOURCE_DIR}}/{p.relative_to(ROOT).as_posix()}"' for p in core_sources],
        ")",
        "set(XIAOTU_GENERATED_SERVER_SOURCES",
        *[f'  "${{CMAKE_SOURCE_DIR}}/{p.relative_to(ROOT).as_posix()}"' for p in server_sources],
        ")",
        "",
    ]
    write(ROOT / "cmake" / "generated_sources.cmake", "\n".join(cmake_lines), check)

    if not check:
        # 只清理本 schema 可能产出的文件，避免误删其他 schema 的生成物。
        for name, keep in generated.items():
            clean_stale(ROOT / targets[name], set(keep), TABLE_SUFFIXES, check)

    print(f"完成：{len(schema['tables'])} 张表")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", default="all", help="schema 名称，或 all（默认，处理 schema/ 下全部定义）")
    parser.add_argument("--check", action="store_true", help="只检查生成物是否与 schema 一致")
    args = parser.parse_args()

    if args.schema == "all":
        schema_paths = sorted((HERE / "schema").glob("*.json"))
    else:
        schema_paths = [HERE / "schema" / f"{args.schema}.json"]

    if not schema_paths:
        print("找不到任何 schema", file=sys.stderr)
        return 1
    for schema_path in schema_paths:
        if not schema_path.exists():
            print(f"找不到 schema: {schema_path}", file=sys.stderr)
            return 1

    env = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )

    for schema_path in schema_paths:
        schema = json.loads(schema_path.read_text(encoding="utf-8"))
        schema["name"] = schema.get("name", schema_path.stem)
        if "editions" in schema:
            generate_editions(schema_path, schema, env, args.check)
        else:
            generate_tables(schema, env, args.check)

    if args.check and DRIFT:
        print(f"漂移：{len(DRIFT)} 个生成物与 schema 不一致", file=sys.stderr)
        return 1
    return 0



if __name__ == "__main__":
    raise SystemExit(main())
